"""Build one Windows EXE containing the authentication DLL and curl dependency.

Uses the dependencies installed by prepare_sdk_tools.py. No network operations.
"""
from pathlib import Path
import os
import subprocess
import shutil
import zipfile
import hashlib
import json


def main():
    root = Path(__file__).resolve().parents[1]
    deps = root / "tools/sdk-build"
    zig = next((deps / "zig").glob("*/zig.exe"))
    curl = next((deps / "curl").glob("curl-*"))
    build = root / "build/embedded"
    build.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, ZIG_GLOBAL_CACHE_DIR=str(deps / "cache"),
               ZIG_LOCAL_CACHE_DIR=str(build / "cache"))
    flags = [str(zig), "c++", "-std=c++17", "-O1", "-Wall", "-Wextra", "-Wpedantic",
             "-I" + str(root / "sdk/include"), "-I" + str(deps / "include"),
             "-I" + str(curl / "include")]
    module = build / "novyx_auth.dll"
    subprocess.run(flags + ["-shared", str(root / "sdk/bootstrap/auth_module.cpp"),
                           str(root / "sdk/src/client.cpp"), str(curl / "lib/libcurl.dll.a"),
                           "-ladvapi32", "-o", str(module)], check=True, env=env)
    with (build / "embedded_payloads.hpp").open("w", encoding="ascii") as header:
        header.write("// Generated by build_embedded_auth.py; do not edit.\n#pragma once\n")
        for name, path in [("auth_payload", module),
                           ("curl_payload", curl / "bin/libcurl-x64.dll")]:
            data = path.read_bytes()
            header.write(f"static const unsigned char {name}[] = {{\n")
            for offset in range(0, len(data), 32):
                header.write(",".join(str(byte) for byte in data[offset:offset + 32]) + ",\n")
            header.write("};\n")
    executable = build / "novyx_bootstrap.exe"
    subprocess.run(flags + ["-I" + str(build), str(root / "sdk/bootstrap/main.cpp"),
                           "-lole32", "-o", str(executable)], check=True, env=env)
    # This EXE contains only the small DLL client. The admin panel packages it
    # with the bootstrap template; it cannot authenticate without the DLL.
    subprocess.run(flags + ["-DNOVYX_DLL_CLIENT", str(root / "sdk/examples/main.cpp"),
                           "-ladvapi32", "-o", str(build / "novyx_dll_example.exe")], check=True, env=env)
    subprocess.run(flags + [str(root / "sdk/examples/simple/main.cpp"),
                           "-ladvapi32", "-o", str(build / "novyx_simple.exe")], check=True, env=env)
    assets = root / "sites/novyx/public/bootstrap"
    assets.mkdir(parents=True, exist_ok=True)
    shutil.copy2(executable, assets / "novyx-template.bin")
    # The template is a binary input to the browser packager, not a download
    # intended to be launched directly.
    (assets / "novyx-template.exe").unlink(missing_ok=True)
    with zipfile.ZipFile(assets / "novyx-bootstrap-sdk.zip", "w", zipfile.ZIP_DEFLATED) as bundle:
        for name in ["abi.h", "bootstrap.hpp", "hardware.hpp"]:
            bundle.write(root / "sdk/include/novyx" / name, "include/novyx/" + name)
        bundle.write(root / "sdk/examples/main.cpp", "example/main.cpp")
        bundle.write(root / "sdk/examples/simple/main.cpp", "simple/main.cpp")
        bundle.write(root / "docs/embedded-auth.md", "README.md")
        bundle.write(build / "novyx_dll_example.exe", "novyx_dll_example.exe")
    manifest = {
        "sdk_url": "/v1/admin/bootstrapper/sdk",
        "template_url": "/v1/admin/bootstrapper/template",
        "template_sha256": hashlib.sha256(executable.read_bytes()).hexdigest(),
        "template_bytes": executable.stat().st_size,
        "max_bytes": 64 * 1024 * 1024,
        "sdk_version": 1,
    }
    (root / "sites/novyx/lib/bootstrap-manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Admin panel assets: {assets}", flush=True)
    print(f"Single-file application: {executable}", flush=True)


if __name__ == "__main__":
    main()
