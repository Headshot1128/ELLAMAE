import './wasm-setup.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { hashPassword, verifyPassword } from '../lib/novyx-crypto.ts';
import { WASMInterface } from '../vendor/hash-wasm/lib/WASMInterface.ts';
import vectors from './password-vectors.json' with {type:'json'};
import { argon2idAsync } from '@noble/hashes/argon2.js';

test('password WASM binaries match the pinned upstream package',()=>{
  const expected={argon2:'83b5829d20b4312aca1a56819f95eef20492e058c70f282c9ed6929f579b20ed',
    blake2b:'b478c0d889d97d7a8db4d10501457ad78dd406d02dcb4c892c0d844805ef05bb'};
  for(const [name,hash] of Object.entries(expected)) {
    assert.equal(createHash('sha256').update(readFileSync(`vendor/hash-wasm/${name}.wasm`)).digest('hex'),hash);
  }
});

test('WASM accepts existing Python Argon2id hashes and rejects wrong passwords',async()=>{
  // Fixtures generated by argon2-cffi: v19, 64 MiB, 3 iterations, one lane.
  for(const vector of vectors) {
    assert(await verifyPassword(vector.encoded,vector.password));
    assert.equal(await verifyPassword(vector.encoded,vector.password+'wrong'),false);
  }
  assert.equal(await verifyPassword('not-a-password-hash','test'),false);
  assert.equal(await verifyPassword(vectors[0].encoded.replace('m=65536','m=1048576'),vectors[0].password),false);
});

test('new hashes retain cost settings, use fresh salt, and wipe reused scratch memory',async()=>{
  const password=vectors[0].password;
  const first=await hashPassword(password),second=await hashPassword(password);
  assert.match(first,/^\$argon2id\$v=19\$m=65536,t=3,p=1\$/);
  assert.notEqual(first,second);
  assert(await verifyPassword(first,password));
  const parts=first.split('$');
  const reference=await argon2idAsync(new TextEncoder().encode(password),Buffer.from(parts[4],'base64'),{m:65536,t:3,p:1,dkLen:32});
  assert.deepEqual(Buffer.from(reference),Buffer.from(parts[5],'base64'));
  const scratch=(await WASMInterface({name:'argon2',data:'',hash:''},1024)).getMemory();
  assert.equal(scratch.length,65536*1024+1024);
  assert(scratch.every(value=>value===0));
});

test('concurrent password requests stay serialized and bounded',async()=>{
  const results=await Promise.allSettled(Array.from({length:5},()=>verifyPassword(vectors[0].encoded,vectors[0].password)));
  assert.equal(results.filter(result=>result.status==='fulfilled'&&result.value===true).length,4);
  assert.equal(results.filter(result=>result.status==='rejected'&&/busy/.test(result.reason.message)).length,1);
});
