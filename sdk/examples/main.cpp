namespace {
std::string Prompt(const std::string& label, bool secret = false) {
    std::cout << label << std::flush;
#ifdef _WIN32
    const auto input = GetStdHandle(STD_INPUT_HANDLE);
    DWORD mode = 0;
    const bool hidden = secret && GetConsoleMode(input, &mode) &&
                        SetConsoleMode(input, mode & ~ENABLE_ECHO_INPUT);
#else
    (void)secret;
#endif
    std::string value;
    std::getline(std::cin, value);
#ifdef _WIN32
    if (hidden) { SetConsoleMode(input, mode); std::cout << '\n'; }
#endif
    return value;
}
std::string Environment(const char* name) {
    const char* value = std::getenv(name);
    return value ? value : "";
}
struct KeepOpen {
    bool enabled;
    ~KeepOpen() { if (enabled && std::cin.good()) Prompt("\nPress Enter to close..."); }
};
std::string HardwareId() {
    auto configured = Environment("AUTH_HARDWARE_ID");
    if (!configured.empty()) return configured;
#ifdef _WIN32
    return novyx::CurrentUserSid();
#else
    std::ifstream machine("/etc/machine-id");
    std::string value;
    if (std::getline(machine, value)) return value;
#endif
    return "";
}
}

int main(int argc, char** argv) {
    const bool interactive = argc == 1 || (argc == 3 && std::string(argv[2]) == "interactive");
    bool registering = argc == 3 && std::string(argv[2]) == "register";
    KeepOpen keep_open{interactive};
    if (argc > 3) {
        std::cerr << "Usage: auth_example https://auth.example.com [register|interactive]\n"
                     "Provide AUTH_USERNAME and AUTH_PASSWORD; registration also needs AUTH_LICENSE_KEY.\n"
                     "Set AUTH_FILE_ID to the ID generated by Protected files > Upload file.\n"
                     "Optional AUTH_DOWNLOAD_PATH sets the output filename.\n"
                     "Use an application account, not a website administrator.\n";
        return 1;
    }
    if (argc == 3 && !registering && !interactive) { std::cerr << "Unknown mode.\n"; return 1; }
    const std::string server = argc == 1 ? "https://novyx.online" : argv[1];
    auto username = Environment("AUTH_USERNAME");
    auto password = Environment("AUTH_PASSWORD");
    auto key = Environment("AUTH_LICENSE_KEY");
    auto file_id = Environment("AUTH_FILE_ID");
    auto output_path = Environment("AUTH_DOWNLOAD_PATH");
    if (output_path.empty()) output_path = "protected-download.bin";
    if (!interactive && file_id.empty()) {
        std::cerr << "Set AUTH_FILE_ID to the generated ID shown after uploading in Protected files.\n";
        return 1;
    }
    const auto hardware = HardwareId();
    if (interactive) {
        std::cout << "NOVYX - File download example\nConnecting to " << server << "\n"
                     "1. Login\n2. Register key\n\n";
        const auto choice = Prompt("Choose 1 or 2: ");
        if (choice != "1" && choice != "2") { std::cerr << "Choose 1 for login or 2 to register a license key.\n"; return 1; }
        registering = choice == "2";
        if (username.empty()) username = Prompt("Username: ");
        if (password.empty()) password = Prompt(registering ? "Password (visible): " : "Password (hidden): ", !registering);
        if (registering && key.empty()) key = Prompt("License key: ");
        if (!registering) key.clear();
    }
    if (username.empty() || password.empty() || (registering && key.empty())) {
        std::cerr << "Username and password are required; Register key also requires a license key.\n";
        return 1;
    }
    if (hardware.size() < 16 || hardware.size() > 256) { std::cerr << "Could not identify this computer's hardware ID.\n"; return 1; }
    const char* ca = std::getenv("AUTH_CA_BUNDLE");
#ifdef NOVYX_DLL_CLIENT
    secureauth::Client auth(server, hardware, ca ? ca : "", Environment("AUTH_APPLICATION_ID"));
#else
    secureauth::Client auth(server, hardware, std::make_shared<secureauth::CurlTransport>(ca ? ca : ""), Environment("AUTH_APPLICATION_ID"));
#endif
    if (!auth.Initialize()) { std::cerr << "Could not initialize: check the HTTPS address and hardware ID length.\n"; return 1; }
    if (registering) {
        if (!auth.RegisterWithLicense(username, password, key).success) {
            std::cerr << "Registration denied. Use an unused valid key, a new username and a password.\n";
            return 1;
        }
        std::cout << "Registered. License activated and bound to this computer. Signing in...\n";
    }
    auto login = auth.Login(username, password);
    if (!login.success) {
        if (login.error == secureauth::Error::NetworkFailure)
            std::cerr << "Could not connect securely. Check your internet connection and TLS certificate settings.\n";
        else std::cerr << "Login denied. Register your key first, or check your application username and password.\n";
        return 1;
    }
    if (!key.empty() && !auth.ActivateLicense(key).success) {
        std::cerr << "License activation denied.\n";
        auth.Logout();
        return 1;
    }
    std::cout << "Login successful.\n";
    if (interactive) {
        if (file_id.empty()) {
            std::cout << "Upload a file in the website's Protected files panel and copy its file ID.\n";
            file_id = Prompt("File ID: ");
        }
        const auto chosen_path = Prompt("Save as (Enter for " + output_path + "): ");
        if (!chosen_path.empty()) output_path = chosen_path;
    }
    if (file_id.empty()) { std::cerr << "A file ID is required.\n"; auth.Logout(); return 1; }
    // Variables are optional; downloading an uploaded file does not require one.
    const char* variable_name = std::getenv("AUTH_VARIABLE_NAME");
    if (variable_name && *variable_name) {
        auto variable = auth.GetVariable(variable_name);
        if (!variable.success) { std::cerr << "Protected variable denied. Check its name, permission and license expiry in the website.\n"; auth.Logout(); return 1; }
    }
    std::cout << "Downloading file " << file_id << "...\n";
    auto file = auth.downloadfile(file_id, output_path);
    if (!file.success) {
        if (file.error == secureauth::Error::NetworkFailure)
            std::cerr << "Download failed: check your connection and TLS settings.\n";
        else if (file.error == secureauth::Error::FileWriteFailure)
            std::cerr << "Could not save output file: " << output_path << '\n';
        else if (file.error == secureauth::Error::InvalidInput)
            std::cerr << "Invalid file ID. Copy the ID from the Protected files panel.\n";
        else std::cerr << "Download denied. Check the file ID, enabled status, required permission and license expiry.\n";
        auth.Logout(); return 1;
    }
    auth.Logout();
    std::cout << "Saved file to " << output_path << '\n';
    return 0;
}
